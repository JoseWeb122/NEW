#!/usr/bin/env node
/**
 * Regenerates src/db/sql/schema.mjs — the idempotent DDL used by the runtime
 * auto-setup — from the Drizzle schema (src/db/schema.ts) via `drizzle-kit export`.
 *
 * Run this after editing src/db/schema.ts:
 *   node scripts/sync-schema-sql.mjs
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const raw = execSync("npx drizzle-kit export --sql", {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
});

const start = raw.search(/^CREATE /m);
if (start === -1) {
  console.error("✖ drizzle-kit export returned no DDL:\n" + raw);
  process.exit(1);
}

const statements = raw
  .slice(start)
  .replace(/-->\s*statement-breakpoint/g, "")
  .split(/;\s*(?:\n|$)/)
  .map((s) => s.trim())
  .filter(Boolean);

const idempotent = statements.map((stmt) => {
  if (/^CREATE TABLE /.test(stmt)) return stmt.replace(/^CREATE TABLE /, "CREATE TABLE IF NOT EXISTS ") + ";";
  if (/^CREATE (UNIQUE )?INDEX /.test(stmt)) return stmt.replace(/^(CREATE (?:UNIQUE )?INDEX )/, "$1IF NOT EXISTS ") + ";";
  if (/^CREATE SCHEMA /.test(stmt)) return stmt.replace(/^CREATE SCHEMA /, "CREATE SCHEMA IF NOT EXISTS ") + ";";
  if (/^CREATE SEQUENCE /.test(stmt)) return stmt.replace(/^CREATE SEQUENCE /, "CREATE SEQUENCE IF NOT EXISTS ") + ";";
  // Enums, foreign keys and other constraints have no IF NOT EXISTS form.
  return `DO $$ BEGIN\n  ${stmt};\nEXCEPTION WHEN duplicate_object OR duplicate_table THEN NULL;\nEND $$;`;
});

const body = idempotent
  .join("\n\n")
  .replace(/\\/g, "\\\\")
  .replace(/`/g, "\\`")
  .replace(/\$\{/g, "\\${");

const file = `// AUTO-GENERATED by scripts/sync-schema-sql.mjs from src/db/schema.ts — do not edit.
// Idempotent DDL executed by the runtime auto-setup (src/db/setup.ts) and scripts/db-setup.mjs.

export const SCHEMA_SQL = \`
${body}
\`;
`;

const target = path.join(root, "src/db/sql/schema.mjs");
mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(target, file);
console.log(`✓ Wrote src/db/sql/schema.mjs (${idempotent.length} statements)`);
